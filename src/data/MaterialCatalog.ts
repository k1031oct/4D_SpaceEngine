import type { AmbientMediumSpec, MaterialSpec, MediumId } from '../core/types';

/**
 * 平衡格子間隔 r_0 と結合電荷密度から実効固体密度を第一原理で算出する
 */
export function computeEmergentDensity(
  equilibriumSpacing: number,
  bondChargeDensity: number,
  atomicWeightScale = 1.0,
): number {
  const r0 = Math.max(0.05, equilibriumSpacing);
  return (bondChargeDensity / (r0 * r0 * r0)) * 0.135 * atomicWeightScale;
}

/**
 * 媒質の動粘性を密度と基準温度から動的に算出する
 */
export function computeDynamicViscosity(density: number, ambientHeat: number): number {
  if (density <= 0) return 0;
  return density * 0.8 + (density > 0.1 ? 0.05 : 0.04) * Math.sqrt(Math.max(0.01, ambientHeat + 0.5));
}

